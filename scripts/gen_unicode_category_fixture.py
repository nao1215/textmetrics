#!/usr/bin/env python3
"""Generate the expected ranges that test the Unicode 17.0.0 tables.

Usage:
  python3 scripts/gen_unicode_category_fixture.py --unicode-data UnicodeData.txt \
      --word-break-property WordBreakProperty.txt \
      --sentence-break-property SentenceBreakProperty.txt [--check]

It reads the same hash-checked UCD files as gen_unicode_category.py but parses
them with its own code and writes plain sorted ranges, not the generated
table's block layout, so test/unicode_category_table_test.gleam checks the
table against the Unicode data rather than against itself.
"""

import argparse
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile

UNICODE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
WORD_BREAK_SHA256 = "72274cac1e6b919507db35655c3e175aa27274668a1ece95c28d2069f2ad9852"
SENTENCE_BREAK_SHA256 = "871c0c985ad95125e25b302414065a10839d068970bceb383ecec138f22a0a18"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "test/unicode_category_ranges.gleam"
MAX_CODE = 0x10FFFF


def read_checked(path, expected):
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != expected:
        raise ValueError(f"{path}: SHA-256 mismatch: expected {expected}, got {digest}")
    return data.decode("utf-8")


def general_categories(text):
    """Return {code: category} for assigned code points, expanding First/Last pairs."""
    categories = {}
    first = None
    for line in text.splitlines():
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = code
        elif name.endswith(", Last>"):
            for point in range(first, code + 1):
                categories[point] = category
            first = None
        else:
            categories[code] = category
    return categories


def property_values(text):
    """Return {code: value} for the code points a UCD property file lists."""
    values = {}
    for line in text.splitlines():
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        span, value = (field.strip() for field in content.split(";"))
        low, _, high = span.partition("..")
        for point in range(int(low, 16), int(high or low, 16) + 1):
            values[point] = value
    return values


def maximal_ranges(predicate):
    ranges = []
    for code in range(MAX_CODE + 1):
        if not predicate(code):
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ranges


def expected_ranges(categories, word_break, sentence_break):
    def non_letter(code):
        category = categories.get(code, "Cn")
        return code > 0x7F and category[0] not in "LM" and category not in ("Nd", "Nl")

    def word(*wanted):
        return lambda code: word_break.get(code) in wanted

    return [
        ("non_letter", "is_non_letter", non_letter),
        ("word_format", "is_word_format", word("Format")),
        ("word_numeric", "is_word_numeric", word("Numeric")),
        ("letter_joiners", "joins_letters", word("MidLetter", "MidNumLet", "Single_Quote")),
        ("number_joiners", "joins_numbers", word("MidNum", "MidNumLet", "Single_Quote")),
        ("sentence_close", "is_sentence_close", lambda code: sentence_break.get(code) == "Close"),
    ]


def render(categories, word_break, sentence_break):
    lines = [
        "//// Generated by scripts/gen_unicode_category_fixture.py from Unicode 17.0.0. Do not edit.",
        "//// The maximal code point ranges for which each function in",
        "//// textmetrics/internal/unicode_category returns True, read straight from",
        "//// UnicodeData.txt, WordBreakProperty.txt and SentenceBreakProperty.txt.",
        "",
    ]
    for name, function, predicate in expected_ranges(categories, word_break, sentence_break):
        ranges = maximal_ranges(predicate)
        lines.append(f"/// Ranges where `{function}` is True.")
        lines.append(f"pub fn {name}() -> List(#(Int, Int)) {{")
        lines.append("  [")
        lines += [f"    #(0x{low:x}, 0x{high:x})," for low, high in ranges]
        lines += ["  ]", "}", ""]
    return "\n".join(lines)


def generate(arguments):
    source = render(
        general_categories(read_checked(arguments.unicode_data, UNICODE_SHA256)),
        property_values(read_checked(arguments.word_break_property, WORD_BREAK_SHA256)),
        property_values(read_checked(arguments.sentence_break_property, SENTENCE_BREAK_SHA256)),
    )
    with tempfile.TemporaryDirectory() as directory:
        candidate = Path(directory) / arguments.output.name
        candidate.write_text(source, encoding="utf-8", newline="\n")
        subprocess.run(["gleam", "format", str(candidate)], check=True, capture_output=True, text=True)
        formatted = candidate.read_bytes()
    if arguments.check:
        if formatted != arguments.output.read_bytes():
            raise ValueError(f"generated output differs from {arguments.output}; regenerate it")
    else:
        arguments.output.write_bytes(formatted)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unicode-data", type=Path, required=True)
    parser.add_argument("--word-break-property", type=Path, required=True)
    parser.add_argument("--sentence-break-property", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    try:
        generate(arguments)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        detail = error.stderr if isinstance(error, subprocess.CalledProcessError) else str(error)
        print(f"Unicode fixture generation failed: {detail or error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
